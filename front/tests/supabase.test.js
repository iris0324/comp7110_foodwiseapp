import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import {seed} from '../js/data/seed.js';
import {executeCommand} from '../js/domain/commands.js';
const A='00000000-0000-4000-8000-000000000001',B='00000000-0000-4000-8000-000000000002';
test('migration preserves legacy data; real PostgreSQL CRUD, atomic replay, revision conflicts and owner RLS',async()=>{
 const db=new PGlite();
 try{
 await db.exec(`create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key);create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;grant usage on schema auth to authenticated;grant execute on function auth.uid() to authenticated;insert into auth.users values('${A}'),('${B}');create table public.food_items(id bigint generated by default as identity primary key,created_at timestamptz default now(),name text,quantity int,expiry_date date,category text,unit text,notes text,user_id uuid);insert into public.food_items(name,quantity) values('legacy',2);`);
 await db.exec(await readFile(new URL('../../supabase/migrations/202610280001_foodwise.sql',import.meta.url),'utf8'));
 assert.equal((await db.query('select count(*)::int n from food_items')).rows[0].n,1);
 await db.exec(`set role authenticated;set request.jwt.claim.sub='${A}';`);
 let initial=seed('en','epoch-A');
 const load=async()=> (await db.query('select foodwise_load($1::jsonb) s',[JSON.stringify(initial)])).rows[0].s;
 let s=await load();assert.equal(s.foodItems.length,0);
 let n=0;
 const run=async(type,payload={})=>{
 const c={type,payload,operationId:'test-'+ ++n,epoch:s.epoch,expectedRevision:s.revision,issuedAt:new Date().toISOString()};
 const out=executeCommand(s,c);
 await db.query('select foodwise_save($1,$2,$3::jsonb)',[s.revision,s.epoch,JSON.stringify(out.state)]);
 s=await load();return {c,out};
 };
 const {c}=await run('food_add',{fields:{name:'Milk',quantity:'1.5',recordedDate:'2026-11-01',category:'dairy',unit:'L'}});
 assert.equal(s.foodItems[0].remainingQuantity,'1.5');assert.equal(s.foodItems[0].recordedDate,'2026-11-01');
 assert.equal(executeCommand(s,c).replayed,true);
 await assert.rejects(db.query('select foodwise_save($1,$2,$3::jsonb)',[0,s.epoch,JSON.stringify(s)]),/conflict/);
 const id=s.foodItems[0].id;
 await run('food_star',{id});assert.equal(s.foodItems[0].isStarred,true);
 await run('food_remaining',{id,remaining:'0.5'});assert.equal(s.foodItems[0].remainingQuantity,'0.5');
 assert.equal(s.foodItems[0].initialQuantity,'1.5');assert.equal(s.foodEvents.length,1);
 await db.exec(`insert into foodwise_media(user_id,id,mime_type,data) values('${A}','photo','image/png','AA==');set request.jwt.claim.sub='${B}'`);
 assert.equal((await db.query('select * from foodwise_media')).rows.length,0);
 assert.equal((await db.query('select * from food_items')).rows.length,0);
 assert.equal((await db.query('select * from foodwise_state')).rows.length,0);
 for(const sql of [`insert into food_items(user_id,name,quantity) values('${A}','attack',1)`,`insert into foodwise_state(user_id,state) values('${A}','{}')`,`insert into foodwise_media(user_id,id,mime_type,data) values('${A}','x','image/png','AA==')`])await assert.rejects(db.exec(sql),/row-level security/);
 assert.equal((await db.query(`update food_items set name='attack' where user_id='${A}' returning id`)).rows.length,0);
 assert.equal((await db.query(`delete from food_items where user_id='${A}' returning id`)).rows.length,0);
 await db.exec(`insert into food_items(user_id,name,quantity) values('${B}','B own',1)`);
 await assert.rejects(db.exec(`update food_items set user_id='${A}' where user_id='${B}'`),/row-level security/);
 await db.exec(`set role anon`);await assert.rejects(db.exec('select * from food_items'),/permission denied/);
 await assert.rejects(db.query('select foodwise_load($1::jsonb)',[JSON.stringify(initial)]),/permission denied/);
 await db.exec(`set role authenticated;set request.jwt.claim.sub='${A}'`);
 await run('food_delete',{id});assert.equal(s.foodItems.length,0);
 await run('cart_save',{rows:[{cartItemId:'cart-test',name:'Bread',quantity:'2',price:'3',priceMeaning:'total'}]});
 await run('checkout');assert.equal(s.purchases.length,1);assert.equal(s.stories.length,1);assert.equal(s.outcomes.length,1);
 const before=s.revision,out=executeCommand(s,{type:'language',payload:{language:'zh'},operationId:'rollback',epoch:s.epoch,expectedRevision:before,issuedAt:new Date().toISOString()});
 await assert.rejects(db.query('select foodwise_save($1,$2,$3::jsonb,$4::jsonb)',[before,s.epoch,JSON.stringify(out.state),JSON.stringify([{id:null,type:'image/png',data:'AA=='}])]),/null/);
 assert.equal((await load()).revision,before);
 await assert.rejects(db.exec('truncate food_items'),/permission denied/);
 await db.exec('reset role');assert.equal((await db.query("select name from food_items where name='legacy'")).rows.length,1);
 }finally{await db.close();}
});

test('Auth SDK: sign-up, login, persisted session, token refresh, invalid password and logout (mock Auth HTTP)',async()=>{
 const {createClient}=await import('@supabase/supabase-js');
 const memory=new Map(),storage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
 const jwt=(exp)=>[Buffer.from('{"alg":"HS256"}').toString('base64url'),Buffer.from(JSON.stringify({sub:A,exp,role:'authenticated'})).toString('base64url'),'test'].join('.');
 const user={id:A,email:'a@example.test',aud:'authenticated',role:'authenticated',app_metadata:{},user_metadata:{},created_at:new Date().toISOString()};
 let refreshes=0;
 const session=()=>({access_token:jwt(Math.floor(Date.now()/1000)+3600),refresh_token:'refresh-'+refreshes,expires_in:3600,token_type:'bearer',user});
 const fetch=async(url,opts)=>{
  const u=new URL(url),body=opts.body?JSON.parse(opts.body):{};
  if(u.pathname.endsWith('/signup'))return new Response(JSON.stringify({user}),{status:200});
  if(u.pathname.endsWith('/logout'))return new Response('{}',{status:200});
  if(u.searchParams.get('grant_type')==='refresh_token'){refreshes++;return new Response(JSON.stringify(session()),{status:200});}
  if(body.password==='invalid')return new Response(JSON.stringify({error_code:'invalid_credentials',msg:'Invalid login credentials'}),{status:400});
  return new Response(JSON.stringify(session()),{status:200});
 };
 const options={global:{fetch},auth:{storage,storageKey:'foodwise-test-auth',persistSession:true,autoRefreshToken:false,detectSessionInUrl:false}};
 const client=createClient('https://test.supabase.co','sb_publishable_test',options);
 assert.equal((await client.auth.signUp({email:user.email,password:'valid-password'})).error,null);
 assert.ok((await client.auth.signInWithPassword({email:user.email,password:'invalid'})).error);
 assert.equal((await client.auth.signInWithPassword({email:user.email,password:'valid-password'})).data.session.user.id,A);
 const restored=createClient('https://test.supabase.co','sb_publishable_test',options);
 assert.equal((await restored.auth.getSession()).data.session.user.id,A);
 assert.equal((await restored.auth.refreshSession()).error,null);assert.equal(refreshes,1);
 assert.equal((await restored.auth.signOut()).error,null);
 assert.equal((await restored.auth.getSession()).data.session,null);
 client.auth.stopAutoRefresh();restored.auth.stopAutoRefresh();
});

